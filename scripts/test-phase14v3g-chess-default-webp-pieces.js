const fs = require('fs');
const path = require('path');
const root = path.resolve(__dirname, '..');
let pass = 0, fail = 0;
const check = (name, ok) => { if (ok) { pass++; console.log('PASS', name); } else { fail++; console.error('FAIL', name); } };
const read = (p) => fs.readFileSync(path.join(root,p),'utf8');
const board = read('src/components/chess/ChessBoard.tsx');
const lobby = read('src/app/(chess)/chess-lobby.tsx');
const game = read('src/app/(chess)/chess-game/[gameId].tsx');
const overlay = read('src/components/chess/ChessChallengeOverlay.tsx');
const context = read('src/context/ChessRealtimeContext.tsx');
const user = read('src/types/user.ts');
const profile = read('src/services/profile/profileService.ts');
const normalize = read('src/utils/profile.ts');
const codes = ['wk','wq','wr','wb','wn','wp','bk','bq','br','bb','bn','bp'];
const assetDir = path.join(root,'assets/images/chess/pieces-webp-default');
check('exactly 12 default WebP chess assets exist', fs.existsSync(assetDir) && codes.every(c => fs.existsSync(path.join(assetDir, `${c}.webp`))) && fs.readdirSync(assetDir).filter(n=>n.endsWith('.webp')).length===12);
check('board maps all 12 local WebP assets', codes.every(c => board.includes(`pieces-webp-default/${c}.webp`)));
check('board has one fixed piece image map', board.includes('const PIECE_IMAGES') && !board.includes('pieceTheme') && !board.includes('CHESS_PIECE_THEME'));
check('lobby no longer exposes piece theme selection', !lobby.includes('ChessPreGameThemeModal') && !lobby.includes('prepTheme') && !lobby.includes('chessPieceTheme'));
check('challenge overlay no longer exposes piece theme selection', !overlay.includes('pieceTheme') && !overlay.includes('CHESS_PIECE_THEME_OPTIONS'));
check('game route no longer carries pieceTheme', !game.includes('pieceTheme') && !game.includes('ChessPreGameThemeModal'));
check('realtime accept invite no longer carries theme', !context.includes('incomingPieceTheme') && !context.includes('pieceTheme?:') && context.includes('acceptInvite: (inviteId: string)'));
check('profile domain no longer writes chess theme preference', !user.includes('chessPieceTheme') && !profile.includes('updateChessPieceTheme') && !normalize.includes('chessPieceTheme'));
check('smooth ChessBoard motion remains enabled', board.includes('Animated.timing(progress') && board.includes('useNativeDriver: true') && (board.includes('optimistic: true') || board.includes('moveRequestRef')));
check('reconcile/FX gate remains in app flow', (game.includes('visibleBattleEvent=!boardMoving') || game.includes('visibleBattleEvent=fxEnabled&&!boardMoving')) && game.includes('battleEvent.revision<=visualRevision'));
check('old theme selector component removed', !fs.existsSync(path.join(root,'src/components/chess/ChessPreGameThemeModal.tsx')));
check('old theme constants removed', !fs.existsSync(path.join(root,'src/constants/chessThemes.ts')));
console.log(`Phase 14V.3G Default WebP Pieces: ${pass} PASS / ${fail} FAIL`);
process.exit(fail ? 1 : 0);
