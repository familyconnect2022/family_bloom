const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const read = p => fs.readFileSync(path.join(root, p), 'utf8');
const checks = [];
const check = (name, ok) => { checks.push([name, !!ok]); console.log(`${ok ? 'PASS' : 'FAIL'} ${name}`); };

const hub = read('src/app/(home)/(games)/home-games.tsx');
const create = read('src/app/(home)/(games)/home-game-create.tsx');
const detail = read('src/app/(home)/(games)/home-game/[sessionId].tsx');
