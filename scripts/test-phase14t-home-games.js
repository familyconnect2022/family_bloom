check('home games hub exists', hub.includes('TRÒ CHƠI NHÀ MÌNH'));
check('six chosen game ids exist', ['know_each_other','guess_person','memory_owner','truth_lie','story_chain','family_bingo'].every(x => bank.includes(x) && service.includes(x) && types.includes(x)));
check('home hub renamed to Trò chơi Nhà Mình', play.includes('Trò chơi Nhà Mình'));
check('games marked usable on home hub', play.includes('CHƠI NGAY'));
check('game creator uses actual family membership snapshot', create.includes('familyService.listMembers') && !create.includes('FamilyMemberPicker'));
check('all loaded family members become participants', create.includes('participantUids: members.map') && create.includes('participantNames: members.map'));
check('question answers are frozen into session', service.includes('prompts,') && types.includes('prompts: HomeGamePrompt[]'));
check('know each other uses five prompts', service.includes('seededPick(KNOW_EACH_OTHER_QUESTIONS, 5'));
check('guess person uses three clues', service.includes('seededPick(GUESS_PERSON_CLUES, 3'));
check('memory game uses real family Moments', service.includes('momentsService.listFamilyTimelineOnce'));
check('memory owner stored in secret not public preview', service.includes('memoryAuthorUid: chosen.authorUid') && !service.includes('memoryPreview = {\n        author'));
check('truth lie has private lie index', service.includes('lieIndex') && detail.includes('CÂU BỊA'));
check('story chain freezes shuffled family turn order', service.includes('turnUids = order.map'));
check('story can be saved as Moment', detail.includes('Lưu thành Moment') && detail.includes('momentsService.create'));
check('bingo is 3x3 nine cells', service.includes('seededPick(BINGO_CELLS.map') && service.includes('9, seed'));
check('bingo checks row column diagonal', detail.includes('[0,1,2]') && detail.includes('[0,4,8]'));
check('question bank is rich: >=64 know questions', (bank.match(/q\("know_/g) || []).length >= 64);
check('clue bank is rich: >=40 clue questions', (bank.match(/q\("clue_/g) || []).length >= 40);
check('truth lie inspiration >=50', bank.includes('TRUTH_LIE_IDEAS') && (bank.split('export const TRUTH_LIE_IDEAS')[1].split('];')[0].match(/"/g) || []).length >= 100);
check('story starters >=50', bank.includes('STORY_STARTERS') && (bank.split('export const STORY_STARTERS')[1].split('];')[0].match(/",/g) || []).length >= 50);
check('bingo bank >=64 cells', bank.includes('BINGO_CELLS') && (bank.split('export const BINGO_CELLS')[1].split('];')[0].match(/",/g) || []).length >= 64);
check('sessions bounded to 80', service.includes('const SESSION_LIMIT = 80'));
check('visible session query is bounded', service.includes('limit(SESSION_LIMIT)'));
check('public response listener bounded', service.includes('where("public", "==", true)') && service.includes('limit(60)'));
check('no per-session listener on home hub', hub.includes('homeGameService.watchVisible') && !hub.includes('watchSession'));
check('shared realtime registry used for hub', hub.includes('subscribeSharedRealtime'));
check('home games hub no longer exposes simulation size controls', !hub.includes('[0, 10, 50, 100]')); 
check('home game service no longer ships simulated-session helper', !service.includes('simulated('));
