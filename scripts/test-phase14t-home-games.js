check('android versionCode remains at or above 143000', appJson.expo.android.versionCode >= 143000);
check('iOS bundle remains canonical and build stays at or above 10', appJson.expo.ios.bundleIdentifier === 'com.family.ios' && Number(appJson.expo.ios.buildNumber) >= 10);
