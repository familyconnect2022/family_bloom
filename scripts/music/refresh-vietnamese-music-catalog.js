#!/usr/bin/env node
const fs = require("fs");
const path = require("path");
const crypto = require("crypto");
const {
  candidateId,
  candidateKey,
  loadCatalog,
  hasStrongVietnameseTitleSignal,
  htmlToTokens,
  extractRankedSection,
  extractPublisherTerminatedSection,
} = require("./catalog-tools");

const root = path.resolve(process.cwd());
const args = process.argv.slice(2);
const argValue = name => {
  const idx = args.indexOf(name);
  return idx >= 0 ? args[idx + 1] : null;
};
const has = name => args.includes(name);
const fixturePath = argValue("--fixture");
const dryRun = has("--dry-run");
const now = new Date().toISOString();

const statePath = path.join(root, "document/music-catalog/source-state.json");
const reportPath = path.join(root, "document/music-catalog/refresh-latest.json");
const additionsPath = path.join(root, "src/data/vietnameseMusicCatalogAdditions.generated.ts");
const signalsPath = path.join(root, "src/data/vietnameseMusicSourceSignals.generated.ts");

const readJson = (file, fallback) => {
  try { return JSON.parse(fs.readFileSync(file, "utf8")); } catch { return fallback; }
};
const sha256 = value => crypto.createHash("sha256").update(value).digest("hex");

const SOURCES = [
  { id: "nct_home", url: "https://www.nhaccuatui.com/", required: true },
  { id: "nct_top100", url: "https://www.nhaccuatui.com/top100/", required: false },
  { id: "zing_chart", url: "https://zingmp3.vn/zing-chart", required: false },
  { id: "zing_new", url: "https://zingmp3.vn/moi-phat-hanh", required: false },
];

const fetchSource = async (source, priorState) => {
  if (fixturePath && source.id === "nct_home") {
    const body = fs.readFileSync(path.resolve(fixturePath), "utf8");
    return { ...source, status: 200, body, etag: null, lastModified: null, finalUrl: `fixture:${fixturePath}`, fingerprint: sha256(body), changed: true };
  }
  if (fixturePath) return { ...source, status: 204, body: "", etag: null, lastModified: null, finalUrl: source.url, fingerprint: null, changed: false, skipped: true };
  const headers = { Accept: "text/html,application/xhtml+xml", "User-Agent": "FamilyBloomMusicCatalog/1.0 (+public metadata refresh)" };
  if (priorState?.etag) headers["If-None-Match"] = priorState.etag;
  if (priorState?.lastModified) headers["If-Modified-Since"] = priorState.lastModified;
  const controller = new AbortController();
  const timer = setTimeout(() => controller.abort(), 15000);
  try {
    const response = await fetch(source.url, { headers, redirect: "follow", signal: controller.signal });
    if (response.status === 304) return { ...source, status: 304, body: "", etag: priorState?.etag ?? null, lastModified: priorState?.lastModified ?? null, finalUrl: priorState?.finalUrl ?? source.url, fingerprint: priorState?.fingerprint ?? null, changed: false };
    const body = await response.text();
    const fingerprint = sha256(body);
    return {
      ...source,
      status: response.status,
      body,
      etag: response.headers.get("etag"),
      lastModified: response.headers.get("last-modified"),
      finalUrl: response.url,
      fingerprint,
      changed: fingerprint !== priorState?.fingerprint,
    };
  } finally { clearTimeout(timer); }
};

const sourceSignalFor = (sourceKind, rank) => ({ kind: sourceKind, ...(Number.isFinite(rank) ? { rank } : {}) });
const mergeSignals = (signals) => {
  const map = new Map();
  for (const signal of signals) {
    const prev = map.get(signal.kind);
    if (!prev || (signal.rank ?? 9999) < (prev.rank ?? 9999)) map.set(signal.kind, signal);
  }
  return [...map.values()];
};

const parseNctHome = html => {
  const tokens = htmlToTokens(html);
  const top50vi = extractRankedSection(tokens, "Top 50 Nhạc Việt", ["Top 50 Nhạc Hoa", "Nghệ Sĩ Thịnh Hành"], 50)
    .map(row => ({ ...row, sourceKind: "nct_home_top50_vi", buckets: ["trending"] }));
  const trending = extractRankedSection(tokens, "Top 50 Bài Hát Thịnh Hành", ["Top 50 Nhạc Việt"], 50)
    .map(row => ({ ...row, sourceKind: "nct_home_trending", buckets: ["trending"] }));
  const recent = extractPublisherTerminatedSection(tokens, "Single Mới Phát Hành", ["VIP: Âm Thanh Lossless"], 30)
    .map(row => ({ ...row, sourceKind: "nct_home_single_new", buckets: ["recent"] }));
  return { top50vi, trending, recent, all: [...top50vi, ...trending, ...recent] };
};

const renderTsString = value => JSON.stringify(value, null, 2)
  .replace(/"([A-Za-z_][A-Za-z0-9_]*)":/g, "$1:")
  .replace(/\\u2026/g, "…");

const writeGeneratedAdditions = (verified, review) => `import type { VietnameseMusicSeed } from "./vietnameseMusicCatalogV1";\n\n/** AUTO-GENERATED by scripts/music/refresh-vietnamese-music-catalog.js.\n * Only VERIFIED_VIETNAMESE additions are eligible for automatic playlists.\n * REVIEW_QUEUE is discovery-only and cannot enter the playlist until language is verified.\n */\nexport const VIETNAMESE_MUSIC_ADDITIONS_GENERATED_AT = ${JSON.stringify(now)} as const;\n\nexport const VERIFIED_VIETNAMESE_MUSIC_ADDITIONS: VietnameseMusicSeed[] = ${renderTsString(verified)};\n\nexport type VietnameseMusicReviewCandidate = {\n  id: string; title: string; artists: string[]; sourceKinds: string[]; firstSeenAt: string; reason: "language_needs_review";\n};\n\nexport const VIETNAMESE_MUSIC_REVIEW_QUEUE: VietnameseMusicReviewCandidate[] = ${renderTsString(review)};\n`;

const writeSignals = map => `import type { VietnameseMusicSignal } from "./vietnameseMusicCatalogV1";\n\n/** AUTO-GENERATED current public-source ranks/signals. */\nexport const VIETNAMESE_MUSIC_SOURCE_SIGNALS_GENERATED_AT = ${JSON.stringify(now)} as const;\nexport const VIETNAMESE_MUSIC_DYNAMIC_SIGNALS: Record<string, VietnameseMusicSignal[]> = ${renderTsString(map)};\n`;

const main = async () => {
  const priorState = readJson(statePath, { sources: {} });
  const catalog = loadCatalog(root);
  const existingVerifiedByKey = new Map(catalog.verified.map(seed => [candidateKey(seed.title, seed.artists), seed]));
  const existingVerifiedById = new Map(catalog.verified.map(seed => [seed.id, seed]));
  const additionsById = new Map(catalog.additions.map(seed => [seed.id, seed]));
  const reviewById = new Map(catalog.review.map(item => [item.id, item]));
  const dynamicSignals = {};
  const sourceResults = [];
  const discovered = [];
  const parseSummaries = {};

  for (const source of SOURCES) {
    let result;
    try { result = await fetchSource(source, priorState.sources?.[source.id]); }
    catch (error) {
      result = { ...source, status: 0, changed: false, error: String(error?.message || error), fingerprint: priorState.sources?.[source.id]?.fingerprint ?? null };
      if (source.required && !fixturePath) console.warn(`[music-refresh] required source failed: ${source.id}: ${result.error}`);
    }
    sourceResults.push(result);
    if (source.id === "nct_home" && result.body) {
      const parsed = parseNctHome(result.body);
      parseSummaries.nct_home = { top50vi: parsed.top50vi.length, trending: parsed.trending.length, recent: parsed.recent.length };
      discovered.push(...parsed.all);
    }
    if (source.id.startsWith("zing") && result.body && /enable javascript to run this app|restrict\.html/i.test(result.body)) {
      result.jsShellOnly = true;
    }
  }

  const grouped = new Map();
  for (const row of discovered) {
    if (!row.title || !row.artists?.length) continue;
    const key = candidateKey(row.title, row.artists);
    const existing = grouped.get(key) || { title: row.title, artists: row.artists, signals: [], buckets: new Set() };
    existing.signals.push(sourceSignalFor(row.sourceKind, row.rank));
    for (const bucket of row.buckets || []) existing.buckets.add(bucket);
    grouped.set(key, existing);
  }

  let addedVerified = 0;
  let addedReview = 0;
  let updatedSignals = 0;
  for (const item of grouped.values()) {
    const key = candidateKey(item.title, item.artists);
    const existingSeed = existingVerifiedByKey.get(key);
    const signals = mergeSignals(item.signals);
    if (existingSeed) {
      dynamicSignals[existingSeed.id] = mergeSignals([...(dynamicSignals[existingSeed.id] || []), ...signals]);
      updatedSignals += 1;
      continue;
    }
    const id = candidateId(item.title, item.artists);
    if (existingVerifiedById.has(id)) {
      dynamicSignals[id] = mergeSignals([...(dynamicSignals[id] || []), ...signals]);
      continue;
    }
    if (hasStrongVietnameseTitleSignal(item.title)) {
      const seed = {
        id,
        title: item.title,
        artists: item.artists,
        language: "vi",
        buckets: Array.from(item.buckets),
        signals,
      };
      additionsById.set(id, seed);
      existingVerifiedByKey.set(key, seed);
      existingVerifiedById.set(id, seed);
      reviewById.delete(id);
      dynamicSignals[id] = signals;
      addedVerified += 1;
    } else if (!reviewById.has(id)) {
      reviewById.set(id, {
        id,
        title: item.title,
        artists: item.artists,
        sourceKinds: signals.map(signal => signal.kind),
        firstSeenAt: now,
        reason: "language_needs_review",
      });
      addedReview += 1;
    } else {
      const previous = reviewById.get(id);
      reviewById.set(id, { ...previous, sourceKinds: Array.from(new Set([...(previous.sourceKinds || []), ...signals.map(signal => signal.kind)])) });
    }
  }

  const nextState = {
    updatedAt: now,
    policy: "append_verified; keep_pending; never delete source history; provider audit controls playable pool",
    sources: Object.fromEntries(sourceResults.map(result => [result.id, {
      url: result.url,
      finalUrl: result.finalUrl ?? result.url,
      status: result.status,
      etag: result.etag ?? null,
      lastModified: result.lastModified ?? null,
      fingerprint: result.fingerprint ?? null,
      checkedAt: now,
      jsShellOnly: !!result.jsShellOnly,
      error: result.error ?? null,
    }])),
  };
  const report = {
    generatedAt: now,
    fixture: fixturePath || null,
    dryRun,
    parseSummaries,
    discoveredUnique: grouped.size,
    verifiedBefore: catalog.verified.length,
    verifiedAfter: catalog.base.length + additionsById.size,
    reviewAfter: reviewById.size,
    addedVerified,
    addedReview,
    updatedSignals,
    sources: nextState.sources,
  };

  console.log(`[music-refresh] discovered=${report.discoveredUnique} verified ${report.verifiedBefore}->${report.verifiedAfter} (+${addedVerified}), review=${report.reviewAfter} (+${addedReview})`);
  console.log(`[music-refresh] nct_home=${JSON.stringify(parseSummaries.nct_home || {})}`);
  if (!dryRun) {
    fs.mkdirSync(path.dirname(statePath), { recursive: true });
    fs.writeFileSync(statePath, JSON.stringify(nextState, null, 2) + "\n");
    fs.writeFileSync(reportPath, JSON.stringify(report, null, 2) + "\n");
    fs.writeFileSync(additionsPath, writeGeneratedAdditions([...additionsById.values()], [...reviewById.values()]));
    fs.writeFileSync(signalsPath, writeSignals(dynamicSignals));
  }
  if (!fixturePath && !parseSummaries.nct_home?.top50vi) process.exitCode = 2;
};

if (require.main === module) main().catch(error => { console.error(error); process.exit(1); });
module.exports = { parseNctHome };
