#!/usr/bin/env node
'use strict';
const __legacyScriptsDir = require('node:path').resolve(__dirname, '..', '..');
// Source-level guards; NOT a substitute for an APK/device benchmark.
const fs = require('fs');
const path = require('path');
const root = path.resolve(__legacyScriptsDir, '..');
const read = (rel) => fs.readFileSync(path.join(root, rel),'utf8');
const raw = 'modules/family-bloom-overlay/android/src/main/res/raw/';
const names = ['game_start','move_self','move_opponent','capture','move_check','castle','promote','premove','illegal','tenseconds','game_end'];
const audio = read('scripts/setup/check-board-audio-apk.js');
const board = read('modules/family-bloom-overlay/android/src/main/java/expo/modules/familybloomoverlay/ChessNativeBoardView.kt');
const native = read('modules/family-bloom-overlay/android/src/main/java/expo/modules/familybloomoverlay/FamilyBloomOverlayModule.kt');
const ctrl = read('src/services/games/nativeChessGameplayController.ts');
const schema = read('modules/family-bloom-overlay/android/src/main/java/expo/modules/familybloomoverlay/NativeChessBoardState.kt');
const tabs = read('src/app/(tabs)/_layout.tsx');
const rootLayout = read('src/app/_layout.tsx');
const bat = read('scripts/android/build/Family_Bloom_Android_Test_App_RELEASE.bat');
const app = JSON.parse(read('app.json')).expo;
let passed = 0, failed = 0;
const check = (good, label) => { if (good) {++passed; console.log('PASS '+label);} else {++failed;console.error('FAIL '+label);} };
console.log('Family Bloom H10 | Chess local-first / native UI guards');
check(app.android.versionCode === 143043 && app.version === '1.3.33','distinct APK identity');
check(native.includes('P2.37R2C-H25-native-3'),'native binary tag synchronized');
check(names.every(n=>fs.existsSync(root+'/'+raw+'fb_board_'+n+'.mp3')), '11 source mp3 embedded in Android res/raw');
check(names.every(n=>board.includes('R.raw.fb_board_'+n)),'11 native cues registered in SoundPool');
check(audio.includes('res/raw/fb_board_') && bat.includes('check-board-audio-apk.js'),'build/preflight/after-build verifies exact APK raw resource names');
check(ctrl.includes('MAX_PREMOVES = 1') && ctrl.includes('queuedPremoves.push('),'single safe premove queue');
check(ctrl.includes('drainPremoveQueue()') && ctrl.includes('safeMove(game, next)'),'premove rechecked against authoritative FEN');
check(ctrl.includes('optimisticFen = null') && ctrl.includes('isLegalServerDelta(currentState, delta)') && ctrl.includes('resetInFlight()'),'no speculative wrong-side board paint; validated delta and rollback');
check(ctrl.includes('expectedVersion: state.revision') && ctrl.includes('CHESS_EVENTS.gameResync'),'server revision and resync remain mandatory');
check(ctrl.includes('pendingClientMoveId !== clientMoveId') && ctrl.includes('staleMoveTimer'),'late ACKs/timers cannot overwrite newer state');
check(board.includes('paintedCells[square] != paintKey') && board.includes('if (image?.tag != piece)'),'dirty-square / piece-cache renderer');
check(board.includes('val background = when {') && board.includes('square in current.queuedPremoveSquares') && !board.includes('val background = when (square)'), 'Kotlin square highlight branches are Boolean expressions');
check(board.includes('startPieceMotion') && board.includes('setDuration(if (legs.size == 2) 178L else 168L)') && board.includes('motionSprites'),'Native piece animation');
check(board.includes('SystemClock.elapsedRealtime()') && board.includes('clockTick'),'Native elapsedRealtime clock');
check(schema.includes('promotionPending') && ctrl.includes('event.action === "promotion"') && board.includes('buildPromotionPicker'),'manual promotion picker');
check(tabs.includes('overflow: "hidden"') && rootLayout.includes('options={{ animation: "none", freezeOnBlur: true }}'),'first-login overflow and auth transition guarded');
check(native.includes('FrameLayout.LayoutParams(1, 1)'),'idle decor host parked at 1x1 during login');
console.log(`H10 guards: ${failed ? 'FAIL' : 'PASS'} (${passed}/${passed+failed})`);
process.exit(failed?1:0);
