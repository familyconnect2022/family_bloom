#!/usr/bin/env node
'use strict';
const fs = require('fs');
const path = require('path');
const root = path.resolve(__dirname, '..');
let pass=0, fail=0;
const read=(r)=>fs.readFileSync(path.join(root,r),'utf8');
const json=(r)=>JSON.parse(read(r));
const check=(ok,msg)=>{ if(ok){pass++; console.log(`PASS ${msg}`);} else {fail++; console.error(`FAIL ${msg}`);} };
console.log('\nFamily Bloom P2.37R2C-H6 — binary identity lock\n');
const app=json('app.json'); const eas=json('eas.json'); const pkg=json('package.json');
const mod=json('modules/family-bloom-overlay/package.json');
const native=read('modules/family-bloom-overlay/android/src/main/java/expo/modules/familybloomoverlay/FamilyBloomOverlayModule.kt');
const screen=read('src/app/(internal)/board-game-bot-test.tsx');
const bat=read('scripts/android/eas/Family_Bloom_EAS_BUILD_TEST.bat');
check(app.expo?.version==='1.3.29' && app.expo?.android?.versionCode===143039, 'app binary identity is unique R2C = 1.3.29 / 143039');
check(eas.cli?.appVersionSource==='local', 'EAS uses local app version source');
check(eas.build?.['family-bloom-test']?.developmentClient===true, 'family-bloom-test is developmentClient=true for Metro workflow');
check(mod.version==='1.3.18', 'local native package = 1.3.14');
check(fs.existsSync(path.join(root,'modules/family-bloom-overlay/android/src/main/AndroidManifest.xml')), 'local Android library includes explicit manifest');
check(native.includes('P2.37R2C-H25-native-1'), 'Kotlin native identity is P2.37R2C-H25-native-1');
check(screen.includes('EXPECTED_ANDROID_VERSION_CODE = "143039"') && screen.includes('EXPECTED_NATIVE_IDENTITY = "P2.37R2C-H25-native-1"'), 'test UI hard-codes expected binary/native identity');
check(screen.includes('Binary gate:') && screen.includes('nativeBinaryReady'), 'test UI exposes PASS/FAIL binary gate');
check(screen.includes('disabled={busy || !nativeBinaryReady}'), 'Surface probes are disabled until correct binary is installed');
check(pkg.scripts?.['eas-build-post-install']?.includes('check-p2_37r2c-native-package.js'), 'EAS post-install runs R2C native package proof');
check(pkg.scripts?.['eas-build-on-success']?.includes('check-p2_37r2c-eas-apk-proof.js'), 'EAS on-success inspects built R2C APK');
check(read('scripts/setup/check-p2_37r2c-apk-native-proof.js').includes("EXPECTED_VERSION_CODE = '143039'") && read('scripts/setup/check-p2_37r2c-apk-native-proof.js').includes('P2.37R2C-H25-native-1'), 'APK proof requires manifest versionCode + exact native identity');
check(!bat.includes('--no-wait') && bat.includes('--clear-cache'), 'EAS helper always waits and always clears cache');
check(bat.includes('143039') && bat.includes('P2.37R2C-H25-native-1'), 'EAS helper prints exact expected artifact identity');
console.log(`\nP2.37R2C-H6 binary identity lock: ${fail?'FAIL':'PASS'} (${pass}/${pass+fail})\n`); process.exit(fail?1:0);
