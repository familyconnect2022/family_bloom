const fs = require('fs');
const path = require('path');
const root = path.resolve(__dirname, '..');
const read = p => fs.readFileSync(path.join(root, p), 'utf8');
let pass=0, fail=0;
const check=(name, ok)=>{ if(ok){pass++; console.log('PASS',name)} else {fail++; console.error('FAIL',name)} };
const board = read('src/components/chess/ChessBoard.tsx');
const pkg = JSON.parse(read('package.json'));
const debug = read('scripts/android/Family_Bloom_Android_Debug_Build_And_Run.bat');
const release = read('scripts/android/Family_Bloom_Android_Test_App_RELEASE.bat');
const codes=['wk','wq','wr','wb','wn','wp','bk','bq','br','bb','bn','bp'];
check('ChessBoard uses native React Native Image for local pieces', /from \"react-native\"/.test(board) && /\bImage\b/.test(board) && !board.includes('from "expo-image"'));
check('all 12 local PNG assets remain mapped', codes.every(c=>board.includes(`pieces-png-default/${c}.png`)) || codes.every(c=>fs.existsSync(path.join(root, `assets/images/chess/pieces-png-default/${c}.png`))));
check('board hardware texture cache removed', !board.includes('renderToHardwareTextureAndroid'));
check('expo-image recycling keys removed from board pieces', !board.includes('recyclingKey='));
check('static piece layer remains persistent and explicit sized', board.includes('styles.pieceLayer') && board.includes('width: boardSize') && board.includes('height: boardSize'));
check('static piece sprites remain memoized', board.includes('const PieceSprite = React.memo'));
check('moving piece slot remains persistently mounted', board.includes('PIECE_IMAGE_ENTRIES.map') && board.includes('styles.persistentMovingImage'));
check('local piece images disable Android fade', board.includes('fadeDuration={0}'));
check('piece layer is not collapsable', board.includes('collapsable={false}'));
check('persistent settle still avoids progress reset at B', !board.slice(board.indexOf('const settleVisualMove ='), board.indexOf('function startSlide')).includes('progress.setValue(0)'));
check('hybrid instant motion remains active', board.includes('const submitHybridMove = async') && board.includes('startSlide({'));
check('legacy rollback remains absent', !board.includes('rollbackVisualMove') && !board.includes('ROLLBACK_ANIMATION_MS'));
check('phase14v3n1 package script wired', pkg.scripts['phase14v3n1:check'] === 'node ./scripts/test-phase14v3n1-chess-piece-visibility-hotfix.js');
check('DEBUG build runs piece visibility hotfix gate', debug.includes('phase14v3n1:check'));
check('RELEASE build runs piece visibility hotfix gate', release.includes('phase14v3n1:check'));
console.log(`Phase 14V.3N.1 Chess Piece Visibility Hotfix: ${pass} PASS / ${fail} FAIL`);
process.exit(fail?1:0);
